	/**
	 * An interface icon.
	 *
	 * @param string $name  Icon name, e.g. "sparkles".
	 * @param int    $size  Size in pixels.
	 * @param string $css_class Extra CSS class.
	 */
	public static function ui( string $name, int $size = 16, string $css_class = '' ): string {
		if ( ! isset( self::UI[ $name ] ) ) {
			return '';
		}

		return sprintf(
			'<svg class="a4smap-icon %1$s" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%3$s</svg>',
			esc_attr( $css_class ),
			$size,
			self::UI[ $name ]
		);
	}

	/**
	 * A network logo, either in its brand colour or as a white logo on a coloured tile (the tile colours are in admin.css).
	 *
	 * @param string $network Network value (facebook, instagram, tiktok).
	 * @param int    $size    Size in pixels.
	 * @param bool   $tile    Draw a rounded coloured tile behind a white logo.
	 */
	public static function network( string $network, int $size = 16, bool $tile = false ): string {
		if ( ! isset( self::BRANDS[ $network ] ) ) {
			return self::ui( 'send', $size );
		}

		$color = self::BRAND_COLORS[ $network ];

		if ( ! $tile ) {
			return sprintf(
				'<svg class="a4smap-icon a4smap-logo a4smap-logo--%1$s" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="%3$s" aria-hidden="true" focusable="false"><path d="%4$s"/></svg>',
				esc_attr( $network ),
				$size,
				esc_attr( $color ),
				self::BRANDS[ $network ]
			);
		}

		return sprintf(
			'<span class="a4smap-logo-tile a4smap-logo-tile--%1$s" style="width:%2$dpx;height:%2$dpx"><svg class="a4smap-icon a4smap-logo" width="%3$d" height="%3$d" viewBox="0 0 24 24" fill="#fff" aria-hidden="true" focusable="false"><path d="%4$s"/></svg></span>',
			esc_attr( $network ),
			$size,
			(int) round( $size * 0.58 ),
			self::BRANDS[ $network ]
		);
	}

